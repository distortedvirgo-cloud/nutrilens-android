package com.nutrilens.app.ai

import com.nutrilens.app.data.MealEntity
import kotlin.math.roundToInt

/**
 * Контекст недавних приёмов пищи для промпта (как recentMealsContext в веб-версии):
 * модель видит, что сегодня уже съедено, и не плюсет это к новой еде.
 */
fun buildRecentMealsContext(meals: List<MealEntity>): String =
    meals.joinToString("; ") { "${it.time} ${it.name} — ${it.calories.roundToInt()} ккал" }

/**
 * Дословный порт промпта анализа еды из веб-версии
 * (src/utils/ai.ts, функция analyzeMealImage).
 *
 * @param userContext        ОБЩАЯ ИНФОРМАЦИЯ О ПОЛЬЗОВАТЕЛЕ.
 * @param userNote           ЗАПРОС ПОЛЬЗОВАТЕЛЯ (текст от пользователя; если пуст,
 *                           используется фолбэк как в веб-версии — по наличию фото).
 * @param recentMealsContext НЕДАВНИЕ ПРИЕМЫ ПИЩИ (только контекст). Для MVP: пустая
 *                           строка → блок недавних приёмов пищи пропускается.
 * @param photoCount         Количество прикреплённых фотографий (веб подставляет
 *                           base64Images.length).
 */
fun buildMealAnalysisPrompt(
    userContext: String,
    userNote: String,
    recentMealsContext: String = "",
    photoCount: Int = 1
): String {
    val userRequest = when {
        userNote.isNotBlank() -> userNote
        photoCount > 0 -> "Прикреплено только фото (без текста)."
        else -> "Текст отсутствует."
    }

    val recentBlock =
        if (recentMealsContext.isBlank()) {
            ""
        } else {
            "НЕДАВНИЕ ПРИЕМЫ ПИЩИ (ТОЛЬКО ДЛЯ КОНТЕКСТА, НЕ ПЛЮСУЙ ИХ К НОВОЙ ЕДЕ): $recentMealsContext\n"
        }

    return """Ты высокоточный эксперт-диетолог и анализатор еды. Твоя задача — определить КБЖУ (калории, белки, жиры, углеводы) СУММАРНО для ВСЕХ продуктов или блюд, представленных на фотографиях и/или описанных в тексте.

ОБЩАЯ ИНФОРМАЦИЯ О ПОЛЬЗОВАТЕЛЕ: $userContext
ЗАПРОС ПОЛЬЗОВАТЕЛЯ: $userRequest
${recentBlock}
Количество предоставленных фотографий: $photoCount

ИНСТРУКЦИЯ К ВЫПОЛНЕНИЮ (ОЧЕНЬ ВАЖНО СТРОГО СЛЕДОВАТЬ):

ШАГ 1 — РАЗБОР. Изучи текст (ЗАПРОС ПОЛЬЗОВАТЕЛЯ) и АБСОЛЮТНО ВСЕ прикреплённые фотографии. Если фото несколько (разные блюда, ракурсы или общий вид стола), сопоставь их между собой, чтобы не посчитать одно и то же блюдо дважды. Составь ПОЛНЫЙ список всех отдельных блюд/продуктов на этом приёме пищи.

ПРИОРИТЕТ ИСТОЧНИКОВ для веса порции (от высшего к низшему):
  1. Явная инструкция пользователя в ЗАПРОСЕ — названный вес («200г», «300 г»), размер порции или множитель («двойная порция», «посчитай полную порцию», «две порции», «я съел половину»). Если есть — используй ЭТОТ вес, не переопределяй его визуальной оценкой с фото.
  2. Видимые упаковки и этикетки на фото — вес/объём/КБЖУ прямо на упаковке.
  3. Визуальная оценка по ориентирам на фото (приборы, посуда, геометрия порции).
  4. Типичная порция — если ничего другого нет.

ШАГ 2 — КАЛИБРОВКА РАЗМЕРА ПО ФОТО (НЕ опирайся на текстовое описание посуды). Пользователь ест из самой разной посуды и НЕ помнит её размеры, поэтому любые текстовые подсказки о посуде считай НЕНАДЁЖНЫМИ. Оценивай вес порции САМ по визуальным ориентирам, которые видишь на фотографии:
  • Если пользователь явно указал вес, размер порции или множитель в ЗАПРОСЕ — используй это как исходный вес. Не переопределяй явную инструкцию визуальной оценкой с фото. Примеры: «посчитай полную порцию» → считай целую порцию, даже если на фото видна половина; «200г» → вес = 200; «двойная порция» → умножь типичную порцию на 2.
  • Ориентиры-предметы рядом: столовые приборы (вилка ~18 см, ложка ~19 см), телефон, ключи, банк-карта (~8.5 см), руки — используй их как масштаб.
  • Геометрия самой еды: толщина, площадь, объём куска/порции (ломоть хлеба ~1.5 см толщиной, куриная грудка — по толщине и площади среза, горка риса — по высоте и диаметру).
  • Стандартная бытовая посуда, ВИДНАЯ на фото (если есть): обеденная тарелка ~23–26 см, десертная ~18–20 см, миска ~300–500 мл, кружка ~250–300 мл, стакан ~200–250 мл, столовая ложка ~15 г/15 мл, чайная ~5 г.
  • Видимые упаковки и этикетки: читай вес/объём на упаковке, банке, пакете — это самый точный ориентир.
  • Если на фото НЕТ ни предметов-ориентиров, ни понятной посуды, ни упаковок — оценивай по типичной порции этого блюда (средняя домашняя/ресторанная порция) и ОБЯЗАТЕЛЬНО явно укажи в portion_basis, что оценка по типичной порции (это снижает confidence_score).
  • Учитывай не только площадь, но и ВЫСОТУ/глубину насыпи: плоский блин и горка риса на одной тарелке весят по-разному.
  • Для каждого блюда в items заполни portion_basis — одной короткой фразой, чем именно оценён вес (например: «по инструкции пользователя: 200 г», «по инструкции: полная порция», «по вилке 18 см рядом», «диаметр тарелки ~24 см, заполнена на 2/3», «этикетка: 200 г», «типичная порция 180 г», «кусок ~10×6×2 см»).

ШАГ 3 — ПОЭЛЕМЕНТНЫЙ РАСЧЁТ (ОБЯЗАТЕЛЕН). Для КАЖДОГО блюда из списка заполни элемент массива 'items':
  • name — название блюда/продукта.
  • estimated_weight_g — оценочный вес порции в граммах (целое число).
  • portion_basis — ЧЕМ оценён вес (см. ШАГ 2): инструкция пользователя («по инструкции: 200 г», «по инструкции: полная порция»), конкретный ориентир с фото («этикетка 200 г», «вилка 18 см рядом», «диаметр тарелки ~24 см») либо «типичная порция ~X г» при отсутствии ориентиров. Без этого поля оценка веса недостоверна.
  • calorie_density — типовая калорийность этого продукта в ккал на 100 г (число, например 250, 90, 520).
  • calories/protein/fat/carbs — КБЖУ именно этой порции (посчитай от плотности и веса; белки/жиры/углеводы — в граммах).
  • breakdown — короткая строка-расчёт: «{вес}г × {плотность} ккал/100г = {итог} ккал» плюс список ключевых ингредиентов и скрытых калорий (масло для жарки ~10 г/порция, соусы, сахар в напитках).
  • ВАЖНО про пользовательские уточнения: если пользователь описал конкретные свойства продукта в ЗАПРОСЕ («фарш белковый и нежирный», «постная говядина», «молоко 1.5%», «куриная грудка без кожи»), эти уточнения ИМЕЮТ ПРИОРИТЕТ над типичными значениями. Считай КБЖУ исходя из описания пользователя, а не из усреднённых значений. Например, «фарш белковый, с низким содержанием жира» → Б ~24, Ж ~8, а не Б 20, Ж 17 для обычного фарша.

ШАГ 4 — ИТОГ. Суммируй calories/protein/fat/carbs по всем items — это финальные поля верхнего уровня. Скрытые калории (масло, соусы) добавляй в соответствующий item. КАТЕГОРИЧЕСКИ ЗАПРЕЩАЕТСЯ добавлять в сумму «Недавние приёмы пищи» — это только контекст.

ШАГ 5 — ПОЛЯ ОТВЕТА:
  • name — перечисление всей найденной еды (например: «Омлет с сыром, кофе, сэндвич с курицей»). Не пустое.
  • reasoning — подробная цепочка рассуждений (блюдо за блюдом: что вижу → вес → плотность → скрытые калории → итог). Это обоснование, а не итог.
  • aiThoughts — КРАТКАЯ сводка для пользователя: список блюд с финальными КБЖУ и весом. Без полного дублирования reasoning.
  • confidence_score (целое 1–10) — уверенность в ТОЧНОСТИ РАСЧЁТА КБЖУ, а не факт распознавания. НИЗКО (3–5) при: грубой оценке порции, оценке по типичной порции без визуальных ориентиров, смешанном/слоёном блюде, неясных скрытых жирах, размытом фото или ракурсе без оценки объёма. ВЫСОКО (8–10) только при чёткой порции, понятном составе и надёжной калибровке размера по явному ориентиру на фото (этикетка, приборы, известная посуда). Поле обязательно — не оставляй пустым. Честная низкая оценка важнее завышенной.
  • health_score (целое 0–100) — насколько сбалансировано и полезно ЭТО блюдо по составу и КБЖУ. Учитывай ингредиенты (овощи, клетчатка, качество белка, скрытый сахар), способ готовки (жарка/фритюр/сливочные соусы — снижают), баланс БЖУ. Ориентиры: 80–100 — сбалансированный состав; 60–79 — хороший; 40–59 — нейтральный; 20–39 — плотное/жирное; 0–19 — тяжёлое. Поле обязательно — не оставляй пустым.
  • health_note — ОДНА короткая нейтральная фраза (до ~100 символов), описывающая состав блюда по-факту: «Много белка и клетчатки, умеренно жиров», «Плотное из-за жарки и сыра», «Мало клетчатки, высокая калорийность». Тон — СПОКОЙНЫЙ И БЕЗ ОСУЖДЕНИЯ: опиши блюдо фактами, НЕ оценивай выбор пользователя, не ругай и не давай советов.

ОКРУГЛЕНИЕ: calories — целое; protein/fat/carbs — до целых, для порций до 20 г допустим 1 знак после запятой.
В любой непонятной ситуации делай лучшую примерную оценку (educated guess) — лучше приблизительные данные, чем нули."""
}